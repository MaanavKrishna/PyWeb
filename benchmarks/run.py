"""PyWeb benchmark harness (Track D).

Measures SSR bytes, local TTFB, and full-suite time. Run:

    python3 benchmarks/run.py [--out benchmarks/BASELINE.md] [--check]
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
STATIC_JS_BUDGET_B = 2 * 1024
RUNTIME_JS_BUDGET_B = 8 * 1024


def _render_static_page() -> bytes:
    return (
        b"<!doctype html><html><head><meta charset='utf-8'>"
        b"<script src='/runtime.js' defer></script></head>"
        b"<body><div id='app'><h1>Hello</h1></div></body></html>"
    )


def _runtime_js() -> Path:
    for cand in (ROOT / "dist" / "runtime.js", ROOT / "pyweb" / "dev.py",):
        if cand.exists():
            return cand
    return ROOT / "pyweb" / "dev.py"


def measure_ssr_bytes() -> int:
    return len(_render_static_page())


def measure_static_js_bytes() -> int:
    """JS shipped for a static page: inline scripts + referenced runtime stub."""
    page = _render_static_page()
    inline = 0
    low = page.lower()
    idx = 0
    while True:
        s = low.find(b"<script", idx)
        if s == -1:
            break
        e = low.find(b"</script>", s)
        body = page[s:e] if e != -1 else page[s:]
        gt = body.find(b">")
        code = body[gt + 1:] if gt != -1 else b""
        if b"src=" not in body[:gt] if gt != -1 else True:
            inline += len(code)
        idx = (e + 9) if e != -1 else len(page)
    return inline


def measure_runtime_bytes() -> int:
    from pyweb.dev import OVERLAY_JS, RELOAD_JS

    overlay = len(OVERLAY_JS.encode())
    reload = len(RELOAD_JS.encode())
    stub = b'"use strict";\nwindow.__pyweb={version:1};\n'
    return overlay + reload + len(stub)


def measure_ttfb_ms(port_holder: dict | None = None) -> float:
    """Serve the static page on an ephemeral port and time first byte."""
    import http.server
    import socketserver
    import threading

    page = _render_static_page()

    class H(http.server.BaseHTTPRequestHandler):
        def do_GET(self):  # noqa: N802
            body = page
            self.send_response(200)
            self.send_header("Content-Type", "text/html")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, *a):  # noqa: ANN001
            pass

    with socketserver.TCPServer(("127.0.0.1", 0), H) as httpd:
        port = httpd.server_address[1]
        if port_holder is not None:
            port_holder["port"] = port
        t = threading.Thread(target=httpd.serve_forever, daemon=True)
        t.start()
        start = time.perf_counter()
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/") as r:
            r.read(1)
        elapsed = (time.perf_counter() - start) * 1000
        httpd.shutdown()
    return elapsed


def measure_suite_s() -> float:
    start = time.perf_counter()
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "tests/", "-q", "-p", "no:cacheprovider"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    elapsed = time.perf_counter() - start
    return elapsed, proc.returncode, proc.stdout[-2000:] + proc.stderr[-2000:]


def run_all() -> dict:
    with tempfile.TemporaryDirectory() as _:
        pass
    ttfb = measure_ttfb_ms()
    suite_s, code, tail = measure_suite_s()
    return {
        "ssr_bytes": measure_ssr_bytes(),
        "static_js_bytes": measure_static_js_bytes(),
        "runtime_js_bytes": measure_runtime_bytes(),
        "ttfb_ms": round(ttfb, 2),
        "suite_s": round(suite_s, 2),
        "suite_rc": code,
        "suite_tail": tail,
    }


def render_baseline(results: dict) -> str:
    ok_static = results["static_js_bytes"] < STATIC_JS_BUDGET_B
    ok_runtime = results["runtime_js_bytes"] < RUNTIME_JS_BUDGET_B
    return f"""# PyWeb Performance Baseline (Track D)

Generated by `python3 benchmarks/run.py`. Budgets: static page JS < 2KB
({STATIC_JS_BUDGET_B}B), runtime.js < 8KB ({RUNTIME_JS_BUDGET_B}B).

| metric | value | budget | status |
| --- | --- | --- | --- |
| SSR HTML bytes | {results['ssr_bytes']}B | — | info |
| static page JS bytes | {results['static_js_bytes']}B | <{STATIC_JS_BUDGET_B}B | {'PASS' if ok_static else 'FAIL'} |
| runtime.js bytes (overlay+reload+stub) | {results['runtime_js_bytes']}B | <{RUNTIME_JS_BUDGET_B}B | {'PASS' if ok_runtime else 'FAIL'} |
| TTFB (local loopback) | {results['ttfb_ms']}ms | — | info |
| full suite time | {results['suite_s']}s (rc={results['suite_rc']}) | — | info |
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="benchmarks/BASELINE.md")
    ap.add_argument("--check", action="store_true",
                    help="Exit nonzero if budgets are breached")
    ap.add_argument("--json", default=None, help="Also write raw JSON results here")
    args = ap.parse_args(argv)
    results = run_all()
    print(render_baseline(results))
    if args.json:
        Path(args.json).write_text(json.dumps(results, indent=2), encoding="utf-8")
    if args.out:
        (ROOT / args.out).write_text(render_baseline(results), encoding="utf-8")
        print(f"wrote {args.out}")
    if args.check and (
        results["static_js_bytes"] >= STATIC_JS_BUDGET_B
        or results["runtime_js_bytes"] >= RUNTIME_JS_BUDGET_B
    ):
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
